/** Validación básica en caliente: slugs y títulos únicos (evita duplicados al crecer). */
export function comprobarIntegridad(): string[] {
  const avisos: string[] = [];
  const slugs = new Map<string, number>();
  const titulos = new Map<string, number>();
  for (const c of CURIOSIDADES) {
    slugs.set(c.slug, (slugs.get(c.slug) ?? 0) + 1);
    titulos.set(c.titulo, (titulos.get(c.titulo) ?? 0) + 1);
  }
  for (const [slug, n] of slugs) if (n > 1) avisos.push(`Slug duplicado (${n}×): ${slug}`);
  for (const [t, n] of titulos) if (n > 1) avisos.push(`Título duplicado (${n}×): ${t}`);
  return avisos;
}
